using RoomHub.Api.Domain.Rooms;
using RoomHub.Api.Domain.Bookings;
using RoomHub.Api.Domain.Common;
using RoomHub.Api.Infrastructure.Repositories;
using RoomHub.Api.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using RoomHub.Api.Features.Bookings.CreateBooking;
using RoomHub.Api.Features.Bookings.CancelBooking;
var now = new DateTimeOffset(2026, 12, 1, 8, 0, 0, TimeSpan.Zero);
var checks = 0;
void Check(bool condition, string name) { if (!condition) throw new Exception(name); checks++; }
var small = Room.Create("Small", 10).Value;
var large = Room.Create("Large", 11).Value;
Booking Make(Room room, DateTimeOffset start, TimeSpan duration) => Booking.Create(room,"Raul",start,start+duration,1,now).Value;
Check(Booking.Create(small,"Raul",now,now.AddHours(4),1,now).IsSuccess,"R6 exactly 4h and start now");
Check(Booking.Create(small,"Raul",now,now.AddHours(4).AddTicks(1),1,now).IsFailure,"R6 above 4h");
Check(Booking.Create(large,"Raul",now,now.AddHours(2),1,now).IsSuccess,"R10 exactly 2h");
Check(Booking.Create(large,"Raul",now,now.AddHours(2).AddTicks(1),1,now).Error.Type==ErrorType.Validation,"R10 above 2h");
Check(Booking.Create(small,"Raul",now.AddTicks(-1),now.AddHours(1),1,now).IsFailure,"R5 past");
var exact=Make(small,now.AddHours(1),TimeSpan.FromHours(1));
Check(exact.Cancel(now).IsSuccess,"R11 exactly 60 minutes");
Check(exact.Cancel(now).Error.Type==ErrorType.Conflict,"R8 repeat cancel");
var late=Make(small,now.AddHours(1).AddTicks(-1),TimeSpan.FromHours(1));
Check(late.Cancel(now).Error.Type==ErrorType.Conflict && late.Status==BookingStatus.Active,"R11 below 60 minutes unchanged");
var options = new DbContextOptionsBuilder<RoomHubDbContext>().UseSqlite("Data Source=:memory:").Options;
await using var db = new RoomHubDbContext(options);
await db.Database.OpenConnectionAsync();
await db.Database.EnsureCreatedAsync();
var rooms=new EfRoomRepository(db); var bookings=new EfBookingRepository(db);
var unitOfWork = new EfUnitOfWork(db);
await rooms.AddAsync(small); await rooms.AddAsync(large); await unitOfWork.SaveChangesAsync();
var handler=new CreateBookingHandler(rooms,bookings,new FixedClock(now),unitOfWork);
Task<Result<CreateBookingResponse>> Create(Guid room,DateTimeOffset start,string who="Raul") => handler.HandleAsync(new(room,who,start,start.AddHours(1),1));
var first=await Create(small.Id,now.AddHours(2));
var second=await Create(large.Id,now.AddHours(4));
Check(first.IsSuccess&&second.IsSuccess,"R9 two across rooms allowed");
Check((await Create(small.Id,now.AddHours(6))).Error.Type==ErrorType.Conflict,"R9 third across rooms denied");
Check((await Create(small.Id,now.AddHours(6),"Other")).IsSuccess,"R9 independent participants");
Check((await Create(small.Id,now.AddDays(1))).IsSuccess,"R9 independent days");
var cancel=new CancelBookingHandler(bookings,new FixedClock(now),unitOfWork);
Check((await cancel.HandleAsync(new(first.Value.Id))).IsSuccess,"R11 handler");
Check((await Create(small.Id,now.AddHours(2))).IsSuccess,"R7 R9 cancelled frees slot and daily count");
Check((await handler.HandleAsync(new(Guid.NewGuid(),"",now,now,0))).Error.Type==ErrorType.NotFound,"404 before validation");
var a=Make(small,now.AddHours(10),TimeSpan.FromHours(1));
var b=Make(small,now.AddHours(11),TimeSpan.FromHours(1));
Check(!a.Overlaps(b),"R7 touching allowed");
Check(a.Overlaps(Make(small,now.AddHours(10.5),TimeSpan.FromHours(1))),"R7 actual overlap");
// 23:30 -02:00 belongs to December 2 in UTC, not December 1.
var offsetStart=new DateTimeOffset(2026,12,1,23,30,0,TimeSpan.FromHours(-2));
var thirdDay=await Create(large.Id,offsetStart);
Check(thirdDay.IsSuccess,"UTC date first offset booking");
Check((await Create(large.Id,new DateTimeOffset(2026,12,2,5,0,0,TimeSpan.Zero))).Error.Type==ErrorType.Conflict,"UTC offset counts against correct day");
Console.WriteLine($"{checks} fixed-clock domain/handler checks passed.");
sealed class FixedClock(DateTimeOffset now):TimeProvider { public override DateTimeOffset GetUtcNow()=>now; }
